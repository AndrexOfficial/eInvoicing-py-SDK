"""Localized labels for the setup surfaces — one catalog, thirty-one languages.

Everything else in this package is machinery: XML that either validates or does
not, check digits that either match or do not. This module is the opposite kind
of thing — it is what a **person** reads while wiring an integration up, and a
person configuring FatturaPA in Bulgaria is not necessarily reading Italian.

Both products embedding this package had reached the same wall from different
sides. Their setup screens showed the provider list as raw registry keys
(``wolters_kluwer``, ``fattureincloud_xml``), five credential inputs regardless
of which two the chosen platform actually wants, and no word anywhere about how
to obtain any of it. That is not a translation gap, it is a *content* gap — and
content that lives in two frontends drifts the same way the country table did
before :mod:`einvoice.reference` existed.

So the strings live here, next to the presets they describe, and the platforms
ask for them in whatever language their operator picked.

    from einvoice.i18n import translate, locale_for_country

    translate("kind.sdi_intermediary", "pl")     # 'Pośrednik SdI (Włochy)'
    locale_for_country("BE")                     # 'nl'  (first official language)

**Which languages, and why those.** The union of two sets: the official
languages of every country :mod:`einvoice.countries` supports (the EU-27 plus
the UK, Switzerland and the US — twenty-four languages), and the UI locales the
embedding products ship. A country whose rules this package states, in a
language its taxpayers cannot read, is only half-supported.

**What is *not* translated.** Platform names (``Fatture in Cloud``, ``Chorus
Pro``), format names (``FatturaPA``, ``Peppol BIS 3.0``, ``XRechnung``) and
credential keys (``api_key``) are proper nouns and identifiers. Translating
them would make the setup instructions *harder* to follow, because the operator
has to find that exact word in the vendor's own console.
"""
