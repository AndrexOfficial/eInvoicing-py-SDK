def available_locales() -> list[str]:
    """Every language tag the catalog answers in."""
    return list(LOCALES)


def normalize_locale(tag: str | None) -> str:
    """Best supported match for an ``Accept-Language``-ish tag.

    ``pt-BR`` → ``pt``, ``zh_Hans`` → ``zh``, ``EN-gb`` → ``en``, junk → ``en``.
    Deliberately forgiving: this sits behind a query parameter, and a locale the
    caller mistyped should degrade to English rather than 400 a settings page.
    """
    if not tag:
        return DEFAULT_LOCALE
    cleaned = str(tag).strip().replace("_", "-").lower()
    if not cleaned:
        return DEFAULT_LOCALE
    if cleaned in LOCALES:
        return cleaned
    base = cleaned.split("-", 1)[0]
    return base if base in LOCALES else DEFAULT_LOCALE


def locale_for_country(code: str | None) -> str:
    """The language an operator in ``code`` most likely reads.

    Falls back to English, which is also the honest answer for a country this
    package does not profile.
    """
    return LOCALES_BY_COUNTRY.get((code or "").upper(), (DEFAULT_LOCALE,))[0]


def translate(key: str, /, locale: str | None = DEFAULT_LOCALE, **params: object) -> str:
    """One catalog string, formatted.

    ``locale`` is deliberately NOT positional-only. It used to be, and that made
    the natural spelling — ``translate("label.setup", locale="it")`` — swallow
    the language into ``**params`` and silently answer in English. A wrong
    language that raises nothing is the worst failure this module can have, so
    only ``key`` stays positional-only (nothing formats ``{key}``; a test holds
    that, and the same test forbids a ``{locale}`` placeholder).

    Falls back to English for a missing translation and returns ``key`` itself
    for a missing key — a visible ``step.unknown_thing`` in a UI is a bug report
    that writes itself, where a silent empty string is a blank panel nobody can
    diagnose.

    Unknown ``{placeholders}`` survive verbatim instead of raising: a
    translation that forgot one, or carries one the caller does not supply,
    should not take a settings page down.
    """
    entry = _CATALOG.get(key)
    if entry is None:
        return key
    text = entry.get(normalize_locale(locale)) or entry[DEFAULT_LOCALE]
    if not params:
        return text
    return _format(text, params)


def _format(text: str, params: dict[str, object]) -> str:
    """``str.format`` that never raises on a placeholder mismatch."""
    try:
        return text.format(**params)
    except (KeyError, IndexError, ValueError):
        out = text
        for name, value in params.items():
            out = out.replace("{" + name + "}", str(value))
        return out


def translation_keys() -> list[str]:
    """Every key in the catalog, sorted. Mostly useful to tests."""
    return sorted(_CATALOG)


def catalog_for(locale: str | None = DEFAULT_LOCALE) -> dict[str, str]:
    """The whole catalog in one language, English-filled.

    For a client that would rather ship the strings than call back per label.
    """
    resolved = normalize_locale(locale)
    return {k: (v.get(resolved) or v[DEFAULT_LOCALE]) for k, v in _CATALOG.items()}


